def normalize_license_id(value: object) -> object:
    """Map a legacy license label to its SPDX identifier; leave anything else for validation."""
    if isinstance(value, str):
        return LEGACY_LICENSE_ALIASES.get(value, value)
    return value


def spdx_license(value: str) -> LicenseKind | None:
    """Return the allowlisted SPDX identifier for `value` (or a legacy alias), else None."""
    return _LICENSE_BY_INPUT.get(value)


def canonical_sha256(payload: object) -> str:
    """Compute a deterministic lowercase SHA-256 hex digest over canonical JSON."""
    serialized = json.dumps(payload, sort_keys=True, separators=(",", ":"), ensure_ascii=True)
    return hashlib.sha256(serialized.encode("utf-8")).hexdigest()


class Box2D(BaseModel):
    """Axis-aligned pixel bounding box in viewport coordinates."""

    model_config = ConfigDict(extra="forbid", strict=True, allow_inf_nan=False)

    x: float
    y: float
    width: float = Field(gt=0.0)
    height: float = Field(gt=0.0)
    label: str = ""

    @property
    def right(self) -> float:
        return self.x + self.width

    @property
    def bottom(self) -> float:
        return self.y + self.height

    def area(self) -> float:
        return self.width * self.height

    def intersection_area(self, other: Box2D) -> float:
        ix = max(0.0, min(self.right, other.right) - max(self.x, other.x))
        iy = max(0.0, min(self.bottom, other.bottom) - max(self.y, other.y))
        return ix * iy

    def intersects(self, other: Box2D) -> bool:
        return self.intersection_area(other) > 0.0

    def inside_viewport(self, viewport_width: int, viewport_height: int) -> bool:
        return (
            self.x >= 0.0
            and self.y >= 0.0
            and self.right <= float(viewport_width)
            and self.bottom <= float(viewport_height)
        )


