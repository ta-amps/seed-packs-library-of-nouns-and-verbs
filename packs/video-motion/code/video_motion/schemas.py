class MotionTrack(BaseModel):
    """Piecewise eased scalar track controlling one SceneActor property."""

    model_config = ConfigDict(extra="forbid", strict=True, allow_inf_nan=False)

    property: TrackProperty
    keyframes: list[TrackKeyframe] = Field(min_length=1)

    @model_validator(mode="after")
    def _validate_sorted(self) -> MotionTrack:
        for idx in range(1, len(self.keyframes)):
            if self.keyframes[idx].t_s < self.keyframes[idx - 1].t_s:
                msg = f"Track {self.property!r} keyframes must be sorted by non-decreasing t_s."
                raise ValueError(msg)
        return self


