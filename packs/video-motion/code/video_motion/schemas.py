class SceneRecipe(BaseModel):
    """Complete frame-addressable specification of a dual-aspect social video scene."""

    model_config = ConfigDict(extra="forbid", strict=True, allow_inf_nan=False)

    recipe_id: str = Field(min_length=1)
    title: str = Field(min_length=1)
    synopsis: str = ""
    fps: int = Field(default=30, ge=12, le=120)
    duration_s: float = Field(gt=0.0, le=180.0)
    seed: int = 42
    # Aspect whose safe canvas the actor x/y tracks are authored in. Other aspects remap from it.
    stage_aspect: AspectId = "reels_9x16"
    background_hex: str = "#0b1020"
    cover_frame_index: int = Field(default=0, ge=0)
    beats: list[BeatMarker] = Field(min_length=1)
    actors: list[SceneActor] = Field(min_length=1)
    captions: list[CaptionCue] = Field(default_factory=list)
    audio_cues: list[AudioCue] = Field(default_factory=list)
    attributions: list[AssetAttribution] = Field(default_factory=list)

    @field_validator("background_hex")
    @classmethod
    def _check_bg_hex(cls, value: str) -> str:
        if not HEX_COLOR_RE.fullmatch(value):
            msg = f"Expected 6-digit #RRGGBB background_hex, got {value!r}."
            raise ValueError(msg)
        return value.lower()

    @property
    def total_frames(self) -> int:
        return max(1, round(self.duration_s * self.fps))

    @model_validator(mode="after")
    def _check_cover_frame(self) -> SceneRecipe:
        if self.cover_frame_index >= self.total_frames:
            msg = (
                f"cover_frame_index ({self.cover_frame_index}) must be < total_frames "
                f"({self.total_frames})."
            )
            raise ValueError(msg)
        return self


