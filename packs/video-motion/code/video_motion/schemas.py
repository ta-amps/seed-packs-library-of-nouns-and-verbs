class AssetAttribution(BaseModel):
    """Open-license provenance and content digest for a cast visual or audio asset.

    `digest_basis` states what `sha256` covers. Only `media_bytes` attests file bytes; the bundled
    examples use `illustrative` placeholders and procedural catalog entries hash their definition.
    """

    model_config = ConfigDict(extra="forbid", strict=True, allow_inf_nan=False)

    asset_id: str = Field(min_length=1)
    license: Annotated[
        LicenseKind,
        WithJsonSchema({"type": "string", "enum": list(ACCEPTED_LICENSE_INPUTS)}),
    ]
    creator: str = Field(min_length=1)
    source_uri: str = "urn:video-motion:procedural"
    sha256: str
    digest_basis: DigestBasis = "declared"

    @field_validator("license", mode="before")
    @classmethod
    def _normalize_license(cls, value: object) -> object:
        return normalize_license_id(value)

    @field_validator("sha256")
    @classmethod
    def _check_sha256(cls, value: str) -> str:
        lowered = value.lower()
        if not SHA256_RE.fullmatch(lowered):
            msg = f"Expected 64-char hex sha256 digest, got {value!r}."
            raise ValueError(msg)
        return lowered


